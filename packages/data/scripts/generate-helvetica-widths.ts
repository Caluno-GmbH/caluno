// One-off generator for `helvetica-widths.ts`. Run from the repo root and then
// format the output (the table is committed so @repo/data needs no pdfkit):
//   bun packages/data/scripts/generate-helvetica-widths.ts
//   bunx biome format --write packages/data/src/repositories/accounting/helvetica-widths.ts
//
// Widths and kerning are read back through pdfkit's own `widthOfString` so the
// table agrees with what the backend renders, kerning included.

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

// pdfkit is a dependency of apps/backend only.
const requireFromBackend = createRequire(
  new URL('../../../apps/backend/package.json', import.meta.url),
);
const PDFDocument = requireFromBackend('pdfkit');

const OUTPUT = fileURLToPath(
  new URL(
    '../src/repositories/accounting/helvetica-widths.ts',
    import.meta.url,
  ),
);

const EM = 1000;

function winAnsiCharacters(): string[] {
  const chars: string[] = [];
  for (let code = 0x20; code <= 0x7e; code++)
    chars.push(String.fromCharCode(code));
  for (let code = 0xa0; code <= 0xff; code++)
    chars.push(String.fromCharCode(code));
  chars.push(...[...'€‚ƒ„…†‡ˆ‰Š‹ŒŽ‘’“”•–—˜™š›œžŸ']);
  return chars.sort((a, b) => a.charCodeAt(0) - b.charCodeAt(0));
}

const quote = (s: string) => `'${s.replace(/[\\']/g, '\\$&')}'`;

const pdf = new PDFDocument();
pdf.font('Helvetica').fontSize(EM);
const measure = (s: string): number => pdf.widthOfString(s);

const chars = winAnsiCharacters();
const widths = new Map(chars.map((ch) => [ch, measure(ch)]));
const widthOf = (ch: string): number => widths.get(ch) ?? 0;

// pdfkit applies AFM kerning between adjacent glyphs, so a pair's kerning is
// whatever `widthOfString` returns beyond the two single advances.
const kerning: [string, number][] = [];
for (const left of chars) {
  for (const right of chars) {
    const kern = measure(left + right) - widthOf(left) - widthOf(right);
    if (Math.abs(kern) > 1e-9) kerning.push([left + right, kern]);
  }
}

const lines = [
  "// Generated by packages/data/scripts/generate-helvetica-widths.ts from pdfkit's Helvetica.afm — do not edit.",
  '',
  '/** Advance width per WinAnsi character, in 1/1000 em. */',
  'export const HELVETICA_WIDTHS: Readonly<Record<string, number>> = {',
  ...chars.map((ch) => `  ${quote(ch)}: ${widthOf(ch)},`),
  '};',
  '',
  '/** Kerning between two adjacent characters (keyed by both), in 1/1000 em. */',
  'export const HELVETICA_KERNING: Readonly<Record<string, number>> = {',
  ...kerning.map(([pair, kern]) => `  ${quote(pair)}: ${kern},`),
  '};',
  '',
];

writeFileSync(OUTPUT, lines.join('\n'));
console.log(`${chars.length} widths, ${kerning.length} kerning pairs`);
